set -euo pipefail

cd -- "$(dirname -- "$0")/.."
export GOTOOLCHAIN=local GOTELEMETRY=off

go_version=$(go version)
go_version=${go_version#go version }
gofmt="$(go env GOROOT)/bin/gofmt"
os_version=$(
    # shellcheck source=/dev/null
    . /etc/os-release
    printf '%s' "$PRETTY_NAME"
)
debian_version=$(< /etc/debian_version)

if (($# == 0)); then
    set -- 386 amd64 arm arm64 loong64 mips mipsle mips64 mips64le ppc64 ppc64le riscv64 s390x
fi

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

for arch in "$@"; do
    case "$arch" in
        386) target=i686-linux-gnu; libc=libc6-dev-i386-cross ;;
        amd64) target=x86_64-linux-gnu; libc=libc6-dev:amd64 ;;
        arm) target=arm-linux-gnueabihf; libc=libc6-dev-armhf-cross ;;
        arm64) target=aarch64-linux-gnu; libc=libc6-dev-arm64-cross ;;
        loong64) target=loongarch64-linux-gnu; libc=libc6-dev-loong64-cross ;;
        mips) target=mips-linux-gnu; libc=libc6-dev-mips-cross ;;
        mipsle) target=mipsel-linux-gnu; libc=libc6-dev-mipsel-cross ;;
        mips64) target=mips64-linux-gnuabi64; libc=libc6-dev-mips64-cross ;;
        mips64le) target=mips64el-linux-gnuabi64; libc=libc6-dev-mips64el-cross ;;
        ppc64) target=powerpc64-linux-gnu; libc=libc6-dev-ppc64-cross ;;
        ppc64le) target=powerpc64le-linux-gnu; libc=libc6-dev-ppc64el-cross ;;
        riscv64) target=riscv64-linux-gnu; libc=libc6-dev-riscv64-cross ;;
        s390x) target=s390x-linux-gnu; libc=libc6-dev-s390x-cross ;;
        *) echo "Unsupported Linux architecture: $arch" >&2; exit 1 ;;
    esac

    cc="$target-gcc"
    gcc=$($cc -dumpfullversion)
    libc_version=$(dpkg-query -W -f='${Version}' "$libc")
    mkdir "$work/$arch"
    CGO_ENABLED=1 GOOS=linux GOARCH="$arch" CC="$cc" \
        go tool cgo -godefs -objdir "$work/$arch/" types_linux.go > "$work/$arch/raw.go"

    {
        printf '// SPDX-License-Identifier: BSD-3-Clause\n'
        printf '// Code generated by cmd/cgo -godefs; DO NOT EDIT.\n'
        printf '// Regenerate with host/linux/generate.sh in host/linux/Dockerfile.\n'
        printf '// OS: %s; release: %s.\n' "$os_version" "$debian_version"
        printf '// Go: %s; GCC: %s; glibc headers: %s (%s).\n' "$go_version" "$gcc" "$libc_version" "$libc"
        printf '// cgo -godefs types_linux.go (GOOS=linux GOARCH=%s CC=%s)\n\n' "$arch" "$cc"
        # Preserve native Go alignment. Only these two type adjustments are needed.
        awk 'NR > 2 {
            changed = 0
            if (gsub(/_Ctype_struct___0/, "utTv")) changed = 1
            if ($1 ~ /^(Line|Id|User|Host)$/ && gsub(/uint8/, "int8")) changed = 1
            if (changed) $0 = $0 " // changed by hand"
            print
        }' "$work/$arch/raw.go"
    } | "$gofmt" > "$work/host_linux_$arch.go"
    echo "Generated host_linux_$arch.go"
done

# Do not leave a partially regenerated set if any compiler failed.
for arch in "$@"; do
    cp "$work/host_linux_$arch.go" "host_linux_$arch.go"
done
